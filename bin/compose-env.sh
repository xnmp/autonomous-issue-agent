#!/usr/bin/env bash
# Compose config/shared.env + config/repos/<name>.env → config/.active.env.
#
# Single source of truth for the env-compose step, so BOTH bin/point-at.sh (which
# SOURCES this to keep REPO/TARGET_DIR/… in its own shell) and the `issue-agent`
# CLI (which EXECUTES it just to produce the file) see one identical, expanded
# .active.env. Sourcing shared FIRST then the per-repo overlay means per-repo
# values win. Snapshots the resolved (expanded) values so the Python daemons (via
# the exported os.environ) and the bash tools (via AGENT_ENV) read the same thing.
#
#   . bin/compose-env.sh <name>     # sourced: also exports AGENT_ENV=.active.env
#   bash bin/compose-env.sh <name>  # executed: just writes .active.env
set -uo pipefail

# Works whether sourced (BASH_SOURCE[0] = this file) or executed.
_CE_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
_CE_NAME="${1:-}"
_CE_SHARED="$_CE_ROOT/config/shared.env"
_CE_REPO_ENV="$_CE_ROOT/config/repos/$_CE_NAME.env"
_CE_ACTIVE="$_CE_ROOT/config/.active.env"

# `return` when sourced, `exit` when executed — one line that does the right thing.
_ce_fail() { echo "compose-env: $1" >&2; return 1 2>/dev/null || exit 1; }

[ -n "$_CE_NAME" ]      || _ce_fail "usage: compose-env.sh <name>"
[ -f "$_CE_SHARED" ]    || _ce_fail "missing $_CE_SHARED"
[ -f "$_CE_REPO_ENV" ]  || _ce_fail "missing $_CE_REPO_ENV (create config/repos/$_CE_NAME.env)"

set -a
# shellcheck disable=SC1090
. "$_CE_SHARED"
# shellcheck disable=SC1090
. "$_CE_REPO_ENV"
set +a

# Emit every exported var the config layer cares about, expanded. Only vars that
# are actually set are written (leaving config.py defaults intact for the rest).
{
  echo "# AUTO-GENERATED by bin/compose-env.sh from shared.env + repos/$_CE_NAME.env — do not edit."
  for v in GH_APP_ID GH_APP_INSTALL_ID GH_APP_KEY_FILE GH_APP_TOKEN_CACHE \
           IDENTITY_MODE FIX_BOT REVIEW_BOT STEWARD_BOT \
           FIX_BOT_TOKEN REVIEW_BOT_TOKEN STEWARD_BOT_TOKEN \
           JIRA_SYNC JIRA_PROJECT_KEY JIRA_CLOUD_ID \
           REPO TARGET_DIR BASE_BRANCH \
           STATE_DIR REVIEW_STATE_DIR STEWARD_STATE_DIR \
           REVIEW_TRIGGER_LABEL REVIEW_ADOPT_UNLABELED REVIEW_PROMPT \
           REVIEW_MODE REVIEW_MULTI_AGENT REVIEW_SCOUT_MODEL \
           REVIEW_GATE_MODEL REVIEW_VALIDATION_MODEL \
           TEST_CMD LINT_CMD EDIT_CHECK_CMD RED_MUST_FAIL VERIFY_RED_AT_COMMIT \
           PERMISSION_MODE AUTO_MERGE MERGE_METHOD POLL_SECONDS \
           FIX_MODEL REVIEW_MODEL STEWARD_MODEL MAX_BUDGET_USD REVIEW_BUDGET_USD \
           STEWARD_TRIAGE STEWARD_PROMOTE STEWARD_TRIAGE_MODEL STEWARD_TRIAGE_BUDGET_USD STEWARD_OWNER \
           FIXER_RUNTIME CODEX_BIN CODEX_MODEL CODEX_PROVIDER_ID CODEX_PROVIDER_NAME \
           CODEX_BASE_URL CODEX_ENV_KEY CODEX_WIRE_API CODEX_SANDBOX \
           OPENAI_API_KEY OPENAI_BASE_URL AGENT_IDLE_TIMEOUT_SECONDS \
           ISSUE_SPEND_CAP_USD DAILY_SPEND_CAP_USD ALERT_CMD \
    AGENT_MAX_RUNTIME_SECONDS ALLOW_UNTESTED GATE_TEST_TIMEOUT_S GATE_GH_RETRY_SLEEP; do
    if [ -n "${!v+x}" ]; then printf '%s=%q\n' "$v" "${!v}"; fi
  done
} > "$_CE_ACTIVE"

export AGENT_ENV="$_CE_ACTIVE"
