#!/usr/bin/env bash
# Install the `issue-agent` CLI so it runs from any directory.
#
#   bin/install.sh            # uv sync (editable) + drop the ~/.local/bin shim
#   make install
#
# The harness is NOT a standalone wheel: the daemon walks __file__ up to THIS
# checkout to load plugin/AGENT.md and config/mcp/*.
# So we install editable into the checkout's .venv (the same env point-at.sh's
# `uv run` reuses) and put a thin launcher shim on PATH that execs that venv's
# entry point with the checkout baked in. Idempotent; re-runnable.
set -uo pipefail

HARNESS_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BIN_DIR="${ISSUE_AGENT_BIN_DIR:-$HOME/.local/bin}"

red() { printf '\033[31m%s\033[0m\n' "$1"; }
grn() { printf '\033[32m%s\033[0m\n' "$1"; }
inf() { printf '\033[36m▸ %s\033[0m\n' "$1"; }

# #156: this used to shim ONE hand-written name while pyproject declared two,
# so `issue-agent-publish` — the executable AGENT.md tells every fixer to
# publish through — was absent on any box bootstrapped with `make install`, and
# paid resolve legs blocked asking the operator to install it. The list is now
# DERIVED from the single declaration that materialises .venv/bin: the keys of
# pyproject's [project.scripts] table. Same drift class compose-env.sh removed
# for env vars — adding an entry point to pyproject is the only edit needed,
# and there is no second list that can disagree with it.
console_scripts() {
  awk '
    /^[[:space:]]*\[/ {
      # Tolerate a trailing comment after the table header — TOML allows it,
      # and requiring end-of-line here made the install fail on one.
      in_scripts = ($0 ~ /^[[:space:]]*\[project\.scripts\][[:space:]]*(#.*)?$/)
      next
    }
    !in_scripts { next }
    /^[[:space:]]*#/ { next }
    /=/ {
      name = $0
      sub(/=.*/, "", name)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", name)
      gsub(/^"|"$/, "", name)
      if (name != "") print name
    }
  ' "$1"
}

# ── 1. tooling ────────────────────────────────────────────────────────────────
for c in uv git gh; do
  command -v "$c" >/dev/null 2>&1 || { red "missing '$c' on PATH — install it first."; exit 1; }
done
grn "  ✓ uv / git / gh present"

# ── 2. editable install into the checkout's .venv ─────────────────────────────
# `uv sync --extra sdk` creates/updates .venv from pyproject and installs the
# project itself (editable), which materialises .venv/bin/issue-agent from the
# [project.scripts] entry. This is the SAME .venv point-at.sh's `uv run` uses.
# `--extra dash` rides along on purpose: the dashboard's FastAPI stack is an
# optional extra, so any exact sync that omits it (this one, or a later
# `uv run --extra sdk` from the test targets) prunes it and the next
# `issue-agent dashboard` restart silently degrades to the static v1 snapshot
# (observed twice, 2026-08-09). Installing both removes the remember-the-extra
# knob; a repo that never runs the dashboard just carries a few idle packages.
inf "uv sync --extra sdk --extra dash  (in $HARNESS_ROOT)"
( cd "$HARNESS_ROOT" && uv sync --extra sdk --extra dash ) || { red "uv sync failed"; exit 1; }

SCRIPTS="$(console_scripts "$HARNESS_ROOT/pyproject.toml")"
[ -n "$SCRIPTS" ] || {
  red "no [project.scripts] entries found in $HARNESS_ROOT/pyproject.toml"; exit 1;
}

# ── 3. launcher shims on PATH ─────────────────────────────────────────────────
# Overwrite unconditionally: idempotent re-runs, and a hand-written operator
# workaround shim (the #156 stopgap) is replaced by the generated one.
mkdir -p "$BIN_DIR"
while IFS= read -r name; do
  [ -n "$name" ] || continue
  entry="$HARNESS_ROOT/.venv/bin/$name"
  [ -x "$entry" ] || { red "expected $entry after uv sync — not found."; exit 1; }
  shim="$BIN_DIR/$name"
  cat > "$shim" <<EOF
#!/usr/bin/env bash
# $name launcher — generated by bin/install.sh. Execs the checkout's venv
# entry point (checkout baked in so __file__ still resolves plugin/ + config/).
exec "$entry" "\$@"
EOF
  chmod +x "$shim"
  grn "  ✓ shim → $shim"
done <<EOF
$SCRIPTS
EOF

# ── 4. PATH check ─────────────────────────────────────────────────────────────
case ":$PATH:" in
  *":$BIN_DIR:"*) grn "  ✓ $BIN_DIR is on PATH" ;;
  *) red "  ⚠ $BIN_DIR is NOT on PATH. Add it to your shell rc:"
     printf '        export PATH="%s:$PATH"\n' "$BIN_DIR" ;;
esac

echo
grn "Done. Next:"
echo "  issue-agent init                 # one-time: create config/shared.env"
echo "  cd /path/to/target-repo"
echo "  issue-agent start                # auto-detects repo + working copy"
