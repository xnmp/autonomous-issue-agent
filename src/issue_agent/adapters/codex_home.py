"""Prepare the external CODEX_HOME a Codex leg runs under.

Each checkout gets a state-owned `<state>/codex-hooks/<key>/config.toml` that
carries the trusted harness contract as `developer_instructions` and disables
Codex's native project-document loading, so target-owned AGENTS.md files reach
the model only as untrusted task data (see `repository_guidance`). Nothing is
written into the target checkout.
"""

from __future__ import annotations

import hashlib
import json
import os
import secrets
import stat
from collections.abc import Callable
from dataclasses import replace
from pathlib import Path

from .repository_guidance import RepositoryGuidanceRuntime
from .runtime_plan import AgentRuntime, RuntimePlan
from ..domain.outcome import AgentResult


def _home_key(cwd: str) -> str:
    resolved = os.path.realpath(cwd)
    return Path(resolved).name + "-" + hashlib.sha256(
        resolved.encode()
    ).hexdigest()[:12]


def _config_toml(developer_instructions: str = "") -> str:
    instructions = (
        f"developer_instructions = {json.dumps(developer_instructions, ensure_ascii=False)}\n"
        if developer_instructions else ""
    )
    return f"""# Auto-generated by issue_agent.
{instructions}
# Target AGENTS.md and fallback project documents are delivered separately as
# untrusted user-task data. Zero disables Codex's native developer-authority
# project document loading for this checkout.
project_doc_max_bytes = 0
"""


def _link_codex_auth(codex_dir: str, auth_file: str) -> None:
    """Expose one trusted Codex login to the isolated external CODEX_HOME.

    The link lives in harness state, never in the target checkout. A link keeps
    credential rotation authoritative at the operator's normal Codex profile
    and avoids accumulating state-owned copies of a bearer credential.
    """

    if not auth_file:
        return
    source = os.path.abspath(auth_file)
    if not os.path.isfile(source):
        return
    destination = os.path.join(codex_dir, "auth.json")
    if os.path.realpath(source) == os.path.realpath(destination):
        return
    temporary = os.path.join(
        codex_dir,
        f".auth.json.{os.getpid()}.{secrets.token_hex(6)}.tmp",
    )
    try:
        os.symlink(source, temporary)
        os.replace(temporary, destination)
    finally:
        if os.path.lexists(temporary):
            os.unlink(temporary)


def write_codex_home(
    cwd: str,
    agents_md: str = "",
    state_dir: str = "",
    auth_file: str = "",
) -> str:
    """Emit the external CODEX_HOME for `cwd` and return its config path.

    ``auth_file``, when present, is linked into the state-owned CODEX_HOME so
    an isolated OAuth run uses the operator's existing login without copying
    it into the checkout. Idempotent.
    """
    if not state_dir:
        raise OSError("STATE_DIR is required for Codex containment")
    # The directory name is historical (it once held the governor hooks). It
    # stays so persisted Codex sessions remain resumable and the absolute
    # CODEX_HOME in unsettled spend-recovery evidence stays valid.
    codex_dir = os.path.join(state_dir, "codex-hooks", _home_key(cwd))
    os.makedirs(codex_dir, exist_ok=True)
    os.chmod(codex_dir, stat.S_IRWXU)
    _link_codex_auth(codex_dir, auth_file)
    config_path = os.path.join(codex_dir, "config.toml")
    with open(config_path, "w") as f:
        f.write(_config_toml(agents_md))
    return config_path


class CodexHomeRuntime(AgentRuntime):
    """Run each leg under its checkout's external CODEX_HOME."""

    def __init__(
        self,
        inner: AgentRuntime,
        prepare: Callable[[str], str],
    ):
        self.inner = inner
        self.prepare = prepare

    async def run(self, task: RuntimePlan) -> AgentResult:
        if not task.cwd:
            raise RuntimeError("Codex containment requires an explicit cwd")
        config_path = self.prepare(task.cwd)
        prepared = replace(
            task,
            env={**task.env, "CODEX_HOME": os.path.dirname(config_path)},
        )
        return await RepositoryGuidanceRuntime(self.inner).run(prepared)
