"""Narrow application ports exposed by the dashboard HTTP layer."""

from __future__ import annotations

from typing import Protocol


class GitHubQueries(Protocol):
    """Complete GitHub read seam required by dashboard issue detail."""

    def issues(
        self, repo: str, limit: int = 1000
    ) -> tuple[object | None, str]: ...
    def prs(
        self, repo: str, limit: int = 200
    ) -> tuple[object | None, str]: ...
    def pr(self, repo: str, number: int) -> tuple[object | None, str]: ...


class RepositoryQueries(Protocol):
    def known(self, name: str) -> bool: ...
    def repos(self) -> dict: ...
    def overview(self, name: str, timezone_name: str | None = None) -> dict: ...


class IssueQueries(Protocol):
    def issues(self, name: str) -> dict: ...
    def issue(self, name: str, number: int) -> dict | None: ...
    def step_events(self, name: str, number: int, idx: int) -> dict | None: ...
    def cost_chart(self, session_id: str) -> tuple[str, str]: ...


class OperatorQueries(Protocol):
    def usage(self) -> dict: ...
    def verification(self) -> dict: ...


class DashboardCommands(Protocol):
    def start(self, name: str) -> tuple[bool, str]: ...
    def promote(self, name: str, number: int) -> tuple[bool, str]: ...
    def priority(
        self, name: str, number: int, priority: str | None
    ) -> tuple[bool, str]: ...


class DashboardBackend(
    RepositoryQueries, IssueQueries, OperatorQueries, DashboardCommands, Protocol
):
    """Complete façade accepted by the HTTP composition root."""
